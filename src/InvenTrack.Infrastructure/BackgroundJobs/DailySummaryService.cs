using InvenTrack.Application.Interfaces;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Configuration;

namespace InvenTrack.Infrastructure.BackgroundJobs;

public class DailySummaryService : BackgroundService
{
    private readonly IServiceProvider _serviceProvider;
    private readonly ILogger<DailySummaryService> _logger;
    private readonly IConfiguration _configuration;
    private TimeSpan _runTime;

    public DailySummaryService(IServiceProvider serviceProvider, ILogger<DailySummaryService> logger, IConfiguration configuration)
    {
        _serviceProvider = serviceProvider;
        _logger = logger;
        _configuration = configuration;
        var timeSetting = _configuration.GetSection("AlertSettings")["DailySummaryTime"] ?? "07:00";
        if (TimeSpan.TryParse(timeSetting, out var parsed))
            _runTime = parsed;
        else
            _runTime = new TimeSpan(7, 0, 0);
    }

    protected override async Task ExecuteAsync(CancellationToken stoppingToken)
    {
        _logger.LogInformation("Daily summary service started. Scheduled for {Time}", _runTime);

        while (!stoppingToken.IsCancellationRequested)
        {
            var now = DateTime.UtcNow;
            var nextRun = now.Date.Add(_runTime);

            if (nextRun <= now)
                nextRun = nextRun.AddDays(1);

            var delay = nextRun - now;
            _logger.LogDebug("Daily summary next run at {Time}", nextRun);

            await Task.Delay(delay, stoppingToken);

            if (stoppingToken.IsCancellationRequested) break;

            try
            {
                using var scope = _serviceProvider.CreateScope();
                var dashboardService = scope.ServiceProvider.GetRequiredService<IDashboardService>();
                var emailService = scope.ServiceProvider.GetRequiredService<IEmailService>();

                var summary = await dashboardService.GetSummaryAsync();

                if (summary.Success && summary.Data != null)
                {
                    var body = $@"
                        <h2>InvenTrack Daily Inventory Summary</h2>
                        <p>Date: {DateTime.UtcNow:dddd, MMMM dd, yyyy}</p>
                        <table border='1' cellpadding='8' cellspacing='0' style='border-collapse:collapse;'>
                            <tr style='background-color:#007bff;color:white;'><th>Metric</th><th>Value</th></tr>
                            <tr><td>Total Products</td><td>{summary.Data.TotalProducts}</td></tr>
                            <tr><td>Total Stock Value</td><td>{summary.Data.TotalStockValue:C}</td></tr>
                            <tr><td>Low Stock Items</td><td>{summary.Data.LowStockItems}</td></tr>
                            <tr><td>Out of Stock Items</td><td>{summary.Data.OutOfStockItems}</td></tr>
                            <tr><td>Recent Movements (7 days)</td><td>{summary.Data.RecentMovements}</td></tr>
                        </table>
                        <p><small>Generated by InvenTrack Enterprise</small></p>";

                    var recipients = _configuration.GetSection("AlertSettings")["LowStockAlertRecipients"]?.Split(',') ?? new[] { "admin@inventrack.local" };
                    foreach (var recipient in recipients)
                    {
                        await emailService.QueueEmailAsync(recipient.Trim(), "InvenTrack Daily Inventory Summary", body);
                    }

                    _logger.LogInformation("Daily summary notification sent");
                }
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error sending daily summary");
            }
        }
    }
}
